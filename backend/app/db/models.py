from __future__ import annotations

import uuid
from datetime import UTC, datetime

from pgvector.sqlalchemy import VECTOR
from sqlalchemy import (
    JSON,
    Boolean,
    Computed,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import TSVECTOR, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

from app.db.enums import DocumentStatus, JobStatus


class Base(DeclarativeBase):
    pass


def _utcnow() -> datetime:
    return datetime.now(UTC).replace(tzinfo=None)


def _new_uuid() -> uuid.UUID:
    return uuid.uuid4()


class Document(Base):
    __tablename__ = "documents"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=_new_uuid
    )
    filename: Mapped[str] = mapped_column(String(512))
    content_type: Mapped[str] = mapped_column(String(128))
    status: Mapped[DocumentStatus] = mapped_column(
        String(20), default=DocumentStatus.PENDING
    )
    source_path: Mapped[str | None] = mapped_column(String(1024), nullable=True)
    #: Where ``source_path`` (a storage key) lives: ``local`` or ``s3`` (migration 0006).
    storage_backend: Mapped[str] = mapped_column(String(16), default="local", server_default="local")
    #: The link a document was ingested from, with query string/credentials removed. NULL for uploads.
    source_url: Mapped[str | None] = mapped_column(String(2048), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), default=_utcnow
    )
    updated_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), default=_utcnow, onupdate=_utcnow
    )

    chunks: Mapped[list[Chunk]] = relationship(back_populates="document", cascade="all, delete-orphan")
    jobs: Mapped[list[Job]] = relationship(back_populates="document", cascade="all, delete-orphan")

    def __repr__(self) -> str:
        return f"<Document {self.filename!r} status={self.status}>"


class Chunk(Base):
    __tablename__ = "chunks"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=_new_uuid
    )
    document_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("documents.id", ondelete="CASCADE")
    )
    index: Mapped[int] = mapped_column()
    text: Mapped[str] = mapped_column(Text)
    metadata_: Mapped[dict[str, object]] = mapped_column("metadata", JSON, default=dict)
    vector: Mapped[list[float] | None] = mapped_column(VECTOR(1024), nullable=True)
    #: Keyword-search columns, generated by Postgres (migration 0005; see services/keyword.py). The
    #: configuration here mirrors the migration default; ``rebuild-fts`` may recreate them with another.
    fts: Mapped[str | None] = mapped_column(
        TSVECTOR, Computed("to_tsvector('english'::regconfig, text)", persisted=True), deferred=True
    )
    fts_len: Mapped[int | None] = mapped_column(
        Integer, Computed("rag_fts_len(to_tsvector('english'::regconfig, text))", persisted=True), deferred=True
    )

    document: Mapped[Document] = relationship(back_populates="chunks")

    def __repr__(self) -> str:
        return f"<Chunk index={self.index} document_id={self.document_id}>"


class Job(Base):
    __tablename__ = "jobs"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=_new_uuid
    )
    document_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("documents.id", ondelete="CASCADE")
    )
    task_id: Mapped[str | None] = mapped_column(String(255), nullable=True)
    status: Mapped[JobStatus] = mapped_column(String(20), default=JobStatus.PENDING)
    error: Mapped[str | None] = mapped_column(Text, nullable=True)
    #: Ingest summary (mode, kept/added/removed chunk counts, embedded count). Null until done.
    stats: Mapped[dict[str, object] | None] = mapped_column(JSON, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), default=_utcnow
    )
    updated_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), default=_utcnow, onupdate=_utcnow
    )

    document: Mapped[Document] = relationship(back_populates="jobs")

    def __repr__(self) -> str:
        return f"<Job {self.status} document_id={self.document_id}>"


class User(Base):
    __tablename__ = "users"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=_new_uuid)
    email: Mapped[str] = mapped_column(String(320), unique=True, index=True)
    password_hash: Mapped[str] = mapped_column(String(256))
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    created_at: Mapped[datetime] = mapped_column(server_default=func.now(), default=_utcnow)

    roles: Mapped[list[Role]] = relationship(
        secondary="user_roles", back_populates="users", lazy="selectin"
    )


class Role(Base):
    __tablename__ = "roles"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=_new_uuid)
    name: Mapped[str] = mapped_column(String(64), unique=True)
    description: Mapped[str] = mapped_column(String(256), default="")
    is_builtin: Mapped[bool] = mapped_column(Boolean, default=False)

    permissions: Mapped[list[RolePermission]] = relationship(
        back_populates="role", cascade="all, delete-orphan", lazy="selectin"
    )
    users: Mapped[list[User]] = relationship(secondary="user_roles", back_populates="roles")


class RolePermission(Base):
    __tablename__ = "role_permissions"
    __table_args__ = (UniqueConstraint("role_id", "permission"),)

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=_new_uuid)
    role_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("roles.id", ondelete="CASCADE"))
    permission: Mapped[str] = mapped_column(String(64))

    role: Mapped[Role] = relationship(back_populates="permissions")


class UserRole(Base):
    __tablename__ = "user_roles"

    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), primary_key=True
    )
    role_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("roles.id", ondelete="RESTRICT"), primary_key=True
    )


class Trace(Base):
    """One chat request or one ingest run: who, how long, which model, how many tokens, outcome."""

    __tablename__ = "traces"
    __table_args__ = (Index("ix_traces_kind_created", "kind", "created_at"),)

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=_new_uuid)
    created_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), default=_utcnow, index=True
    )
    kind: Mapped[str] = mapped_column(String(16))  # "chat" | "search" | "ingest"
    status: Mapped[str] = mapped_column(String(16))  # "ok" | "error"
    duration_ms: Mapped[int] = mapped_column()
    user_email: Mapped[str | None] = mapped_column(String(320), nullable=True)
    document_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True)
    model: Mapped[str | None] = mapped_column(String(128), nullable=True)
    prompt_tokens: Mapped[int | None] = mapped_column(nullable=True)
    completion_tokens: Mapped[int | None] = mapped_column(nullable=True)
    hits: Mapped[int | None] = mapped_column(nullable=True)
    #: LLM cost in USD; NULL = unknown (not 0): see ``Completion.cost_usd``.
    cost_usd: Mapped[float | None] = mapped_column(Numeric(14, 8, asdecimal=False), nullable=True)
    error: Mapped[str | None] = mapped_column(Text, nullable=True)
    #: The question text; stored only when TRACE_CAPTURE_CONTENT is on.
    question: Mapped[str | None] = mapped_column(Text, nullable=True)
    meta: Mapped[dict[str, object]] = mapped_column(JSON, default=dict)
